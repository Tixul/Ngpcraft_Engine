"""
core/battle_engine_gen.py — Generate battle_engine.h from project battle_engine
mechanic config.

Emits a header consumed by a hand-maintained static template ``battle_engine.c``
(shipped in ``templates/.../src/ngpng/``). The header bakes all user-config
into ``#define`` constants + a tiny config struct so the .c stays generic.

Output layout::

    /* ---- Hero stats ---- */
    #define BE_HERO_MAX_HP           18u
    #define BE_HERO_ATK_MIN           2u
    #define BE_HERO_ATK_RANGE         4u
    #define BE_HERO_DEFENSE           0u
    #define BE_HERO_CRIT_PCT          5u
    #define BE_HERO_CRIT_MULT_X10    20u
    #define BE_HERO_MISS_PCT          5u
    #define BE_HERO_SPRITE_ID         0u
    #define BE_GUARD_REDUCTION        1u
    #define BE_RUN_SUCCESS_PCT       75u

    /* ---- Menu labels (i18n via export) ---- */
    #define BE_LABEL_ATTACK  "ATTACK"
    ...

    /* ---- Messages (battle dialog box ; %s = enemy/item name) ---- */
    #define BE_MSG_ATTACK_HIT   "Hero attacks."
    ...

    /* ---- Inputs ---- */
    #define BE_INPUT_CONFIRM PAD_A
    #define BE_INPUT_CANCEL  PAD_B

    /* ---- Variable bindings (0xFF = no binding) ---- */
    #define BE_XP_VAR_INDEX      3u
    #define BE_XP_OVERFLOW_CLAMP 1u  /* vs WRAP=0 */
    #define BE_GOLD_VAR_INDEX    0xFFu  /* unbound */

    /* ---- Audio refs (0 = silent) ---- */
    #define BE_BGM_BATTLE       0u
    ...

    /* ---- Event hooks (0 = no hook) ---- */
    #define BE_ON_BATTLE_START_EVENT  0u
    ...

    /* ---- Starter inventory ---- */
    #define BE_STARTER_INVENTORY_COUNT 2u
    typedef struct { u8 item_id; u8 qty; } NgpcBattleInvEntry;
    static const NgpcBattleInvEntry g_be_starter_inventory[BE_STARTER_INVENTORY_COUNT] = {
        { ITEM_IDX_POTION, 3u },
        ...
    };
"""
from __future__ import annotations

from pathlib import Path

from core.battle_anchors import (
    BATTLE_ANCHOR_KIND_INFO,
    BATTLE_ANCHOR_KINDS,
)
from core.mechanics import get_mechanic_config


_OUTPUT_FILENAME = "battle_engine.h"

_OVERFLOW_TO_FLAG = {"CLAMP": 1, "WRAP": 0}


def _escape_c(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
         .replace("\"", "\\\"")
         .replace("\n", "\\n")
         .replace("\r", "")
         .replace("\t", "\\t")
    )


def _clamp_u8(v, default: int = 0) -> int:
    try:
        n = int(v if v is not None else default)
    except (TypeError, ValueError):
        n = default
    return max(0, min(255, n))


def _var_index_or_none(value) -> int:
    """Return a u8 slot index (0-15) or 0xFF if value is None / out of range."""
    if isinstance(value, int) and 0 <= value <= 15:
        return value
    return 0xFF


def make_battle_engine_h(*, project_data: dict) -> str:
    cfg = get_mechanic_config(project_data, "battle_engine")

    lines: list[str] = [
        "/* battle_engine.h — auto-generated by NgpCraft Engine */",
        "/* DO NOT EDIT — re-export from the project to update. */",
        "/* Consumed by templates/.../src/ngpng/battle_engine.c (static template). */",
        "#ifndef BATTLE_ENGINE_GEN_H",
        "#define BATTLE_ENGINE_GEN_H",
        "",
        "/* ============================================================ */",
        "/* Hero stats                                                    */",
        "/* ============================================================ */",
        f"#define BE_HERO_MAX_HP            {_clamp_u8(cfg.get('hero_max_hp'),         18):>3}u",
        f"#define BE_HERO_ATK_MIN           {_clamp_u8(cfg.get('hero_attack_min'),      2):>3}u",
        f"#define BE_HERO_ATK_RANGE         {_clamp_u8(cfg.get('hero_attack_range'),    4):>3}u",
        f"#define BE_HERO_DEFENSE           {_clamp_u8(cfg.get('hero_defense'),         0):>3}u",
        f"#define BE_HERO_CRIT_PCT          {_clamp_u8(cfg.get('hero_crit_chance_pct'), 5):>3}u",
        f"#define BE_HERO_CRIT_MULT_X10     {_clamp_u8(cfg.get('hero_crit_multiplier'),20):>3}u",
        f"#define BE_HERO_MISS_PCT          {_clamp_u8(cfg.get('hero_miss_chance_pct'), 5):>3}u",
        f"#define BE_HERO_SPRITE_ID         {_clamp_u8(cfg.get('hero_sprite_id'),       0):>3}u",
        f"#define BE_GUARD_REDUCTION        {_clamp_u8(cfg.get('guard_reduction'),      1):>3}u",
        f"#define BE_RUN_SUCCESS_PCT        {_clamp_u8(cfg.get('run_success_pct'),     75):>3}u",
        f"#define BE_ENEMY_COUNT_PRESET     {_clamp_u8(cfg.get('enemy_count_preset'),   1):>3}u",
        "",
        "/* ============================================================ */",
        "/* Menu labels (FR/EN/etc — i18n via project export)             */",
        "/* ============================================================ */",
        f"#define BE_LABEL_ATTACK  \"{_escape_c(str(cfg.get('cmd_label_attack', 'ATTACK') or 'ATTACK'))}\"",
        f"#define BE_LABEL_ITEM    \"{_escape_c(str(cfg.get('cmd_label_item',   'ITEM')   or 'ITEM'))}\"",
        f"#define BE_LABEL_GUARD   \"{_escape_c(str(cfg.get('cmd_label_guard',  'GUARD')  or 'GUARD'))}\"",
        f"#define BE_LABEL_RUN     \"{_escape_c(str(cfg.get('cmd_label_run',    'RUN')    or 'RUN'))}\"",
        "",
        "/* ============================================================ */",
        "/* Combat messages (battle dialog box templates)                */",
        "/* Use %s for {enemy} / {item} placeholders.                     */",
        "/* ============================================================ */",
    ]

    # Convert {enemy} / {item} placeholders to printf-style %s for the runtime.
    msg_keys = [
        ("BE_MSG_ATTACK_HIT",  "msg_attack_hit",  "Hero attacks."),
        ("BE_MSG_ATTACK_KILL", "msg_attack_kill", "Hero attacks. %s defeated."),
        ("BE_MSG_ENEMY_HIT",   "msg_enemy_hit",   "%s strikes back."),
        ("BE_MSG_ENEMY_KILL",  "msg_enemy_kill",  "%s strikes. Hero falls."),
        ("BE_MSG_GUARD",       "msg_guard",       "Hero guards."),
        ("BE_MSG_RUN",         "msg_run",         "Hero runs away."),
        ("BE_MSG_RUN_FAIL",    "msg_run_fail",    "Couldn't escape!"),
        ("BE_MSG_CRIT_SUFFIX", "msg_crit",        " Critical!"),
        ("BE_MSG_MISS",        "msg_miss",        "Hero missed."),
        ("BE_MSG_GOT_ITEM",    "msg_got_item",    "Got %s!"),
    ]
    for c_name, cfg_key, default_val in msg_keys:
        raw = str(cfg.get(cfg_key, default_val) or default_val)
        # Replace {enemy} and {item} placeholders with %s for runtime printf-like.
        s = raw.replace("{enemy}", "%s").replace("{item}", "%s")
        lines.append(f"#define {c_name:<24} \"{_escape_c(s)}\"")

    lines += [
        "",
        "/* ============================================================ */",
        "/* Inputs (PAD_* constants from ngpc_input.h)                   */",
        "/* ============================================================ */",
        f"#define BE_INPUT_CONFIRM  {str(cfg.get('input_confirm', 'PAD_A') or 'PAD_A')}",
        f"#define BE_INPUT_CANCEL   {str(cfg.get('input_cancel',  'PAD_B') or 'PAD_B')}",
        "",
        "/* ============================================================ */",
        "/* Interface customization (v1.1) — menu items + display toggles */",
        "/* ============================================================ */",
        f"#define BE_CMD_ATTACK_ENABLED  {1 if cfg.get('cmd_attack_enabled', True) else 0}u",
        f"#define BE_CMD_ITEM_ENABLED    {1 if cfg.get('cmd_item_enabled',   True) else 0}u",
        f"#define BE_CMD_GUARD_ENABLED   {1 if cfg.get('cmd_guard_enabled',  True) else 0}u",
        f"#define BE_CMD_RUN_ENABLED     {1 if cfg.get('cmd_run_enabled',    True) else 0}u",
        f"#define BE_SHOW_HERO_HP_VALUE  {1 if cfg.get('show_hero_hp_value', True) else 0}u",
        f"#define BE_SHOW_ENEMY_HP_VALUE {1 if cfg.get('show_enemy_hp_value',True) else 0}u",
        f"#define BE_SHOW_ENEMY_NAME     {1 if cfg.get('show_enemy_name',    True) else 0}u",
        f"#define BE_SHOW_INVENTORY_SIDE {1 if cfg.get('show_inventory_side',True) else 0}u",
        f"#define BE_CURSOR_CHAR    '{(str(cfg.get('cursor_char', '>') or '>')[:1] or '>').replace(chr(39), chr(92)+chr(39))}'",
        f"#define BE_DIALOG_PRESS_HINT \"{_escape_c(str(cfg.get('dialog_press_hint', 'A CONTINUE') or 'A CONTINUE'))}\"",
        "",
        "/* ============================================================ */",
        "/* Background tilemap reference (v1.1)                          */",
        "/* Empty = use bg_palette color only. Non-empty = the user has  */",
        "/* prepared a tilemap with this name in their project ; the     */",
        "/* runtime can call NGP_TILEMAP_BLIT_SCR1(name) to draw it.     */",
        "/* ============================================================ */",
        f"#define BE_BG_TILEMAP_NAME \"{_escape_c(str(cfg.get('bg_tilemap', '') or ''))}\"",
        f"#define BE_BG_TILEMAP_PRESENT  {1 if str(cfg.get('bg_tilemap', '') or '').strip() else 0}u",
        "",
        "/* ============================================================ */",
        "/* Variable bindings (0xFF = no binding ; consumes s_ngpng_vars) */",
        "/* ============================================================ */",
    ]
    xp_idx   = _var_index_or_none(cfg.get("xp_variable"))
    gold_idx = _var_index_or_none(cfg.get("gold_variable"))
    xp_ovf   = _OVERFLOW_TO_FLAG.get(str(cfg.get("xp_overflow_behavior",   "CLAMP")), 1)
    gold_ovf = _OVERFLOW_TO_FLAG.get(str(cfg.get("gold_overflow_behavior", "CLAMP")), 1)
    lines += [
        f"#define BE_XP_VAR_INDEX           0x{xp_idx:02x}u  /* 0xFF = unbound */",
        f"#define BE_XP_OVERFLOW_CLAMP      {xp_ovf}u           /* 1=clamp, 0=wrap */",
        f"#define BE_GOLD_VAR_INDEX         0x{gold_idx:02x}u  /* 0xFF = unbound */",
        f"#define BE_GOLD_OVERFLOW_CLAMP    {gold_ovf}u",
        "",
        "/* ============================================================ */",
        "/* Audio refs (0 = silent — runtime skips Sfx_Play() calls)     */",
        "/* ============================================================ */",
    ]
    audio_keys = [
        ("BE_BGM_BATTLE",         "bgm_battle"),
        ("BE_BGM_VICTORY",        "bgm_victory"),
        ("BE_BGM_DEFEAT",         "bgm_defeat"),
        ("BE_SFX_MENU_MOVE",      "sfx_menu_move"),
        ("BE_SFX_MENU_CONFIRM",   "sfx_menu_confirm"),
        ("BE_SFX_MENU_CANCEL",    "sfx_menu_cancel"),
        ("BE_SFX_PLAYER_ATTACK",  "sfx_player_attack"),
        ("BE_SFX_ENEMY_ATTACK",   "sfx_enemy_attack"),
        ("BE_SFX_GUARD",          "sfx_guard"),
        ("BE_SFX_ITEM_USE",       "sfx_item_use"),
        ("BE_SFX_ENEMY_DEFEATED", "sfx_enemy_defeated"),
        ("BE_SFX_PLAYER_DEFEATED","sfx_player_defeated"),
    ]
    for c_name, cfg_key in audio_keys:
        v = _clamp_u8(cfg.get(cfg_key), 0)
        lines.append(f"#define {c_name:<24}   {v:>3}u")

    lines += [
        "",
        "/* ============================================================ */",
        "/* Custom event hooks (0 = no hook ; emit_custom_event(id))     */",
        "/* ============================================================ */",
        f"#define BE_ON_BATTLE_START_EVENT  {_clamp_u8(cfg.get('on_battle_start_event'), 0):>3}u",
        f"#define BE_ON_VICTORY_EVENT       {_clamp_u8(cfg.get('on_victory_event'),      0):>3}u",
        f"#define BE_ON_DEFEAT_EVENT        {_clamp_u8(cfg.get('on_defeat_event'),       0):>3}u",
        "",
        "/* ============================================================ */",
        "/* Starter inventory                                            */",
        "/* ============================================================ */",
        "typedef struct { u8 item_id; u8 qty; } NgpcBattleInvEntry;",
    ]

    inv = cfg.get("starter_inventory", []) or []
    if not isinstance(inv, list):
        inv = []
    valid_inv = [e for e in inv if isinstance(e, dict)]
    lines.append(f"#define BE_STARTER_INVENTORY_COUNT {len(valid_inv)}u")
    if valid_inv:
        lines.append("static const NgpcBattleInvEntry g_be_starter_inventory[BE_STARTER_INVENTORY_COUNT] = {")
        for i, e in enumerate(valid_inv):
            sep = "," if i < len(valid_inv) - 1 else ""
            item_id = _clamp_u8(e.get("item_id"), 0)
            qty     = max(1, _clamp_u8(e.get("qty"), 1))
            lines.append(f"    {{ {item_id:>3}u, {qty:>3}u }}{sep}")
        lines += ["};", ""]
    else:
        lines.append("/* (starter inventory empty) */")
        lines.append("")

    # ----- Anchor positions (STATIC, v1) -----
    # v1 design choice : the layout is locked. Positions come from
    # BATTLE_ANCHOR_KIND_INFO (jrpg_demo.c-derived), already in pixels.
    # User customization power is in the Mechanics tab inline_config
    # (menu items, display toggles, audio, formulas, messages) — NOT in
    # widget positioning. To re-introduce visual layout editing in v2, this
    # block would read from scenes[battle].entities like in the v1.0 draft.
    lines += [
        "",
        "/* ============================================================ */",
        "/* Anchor widget positions (PIXELS, locked v1 — derived jrpg_demo.c)*/",
        "/* User customization happens in the Mechanics tab inline_config,  */",
        "/* not via widget repositioning (visual layout editor = v2).       */",
        "/* ============================================================ */",
    ]
    for kind in BATTLE_ANCHOR_KINDS:
        info = BATTLE_ANCHOR_KIND_INFO[kind]
        upper = kind.upper()
        lines += [
            f"#define BE_ANCHOR_{upper}_X       {int(info['x']):>3}u",
            f"#define BE_ANCHOR_{upper}_Y       {int(info['y']):>3}u",
            f"#define BE_ANCHOR_{upper}_W       {int(info['w']):>3}u",
            f"#define BE_ANCHOR_{upper}_H       {int(info['h']):>3}u",
        ]

    # Bridge declarations — the static template .c implements these ;
    # the runtime calls them from the player update loop.
    lines += [
        "",
        "/* ============================================================ */",
        "/* Public API (implemented in battle_engine.c static template)  */",
        "/* ============================================================ */",
        "void battle_engine_init(void);",
        "void battle_engine_enter(u8 monster_idx);",
        "void battle_engine_update(void);",
        "void battle_engine_render(void);",
        "u8   battle_engine_is_active(void);   /* non-zero while combat in progress */",
        "",
        "#endif /* BATTLE_ENGINE_GEN_H */",
        "",
    ]
    return "\n".join(lines)


def write_battle_engine_h(*, project_data: dict, export_dir: Path) -> Path:
    export_dir = Path(export_dir)
    export_dir.mkdir(parents=True, exist_ok=True)
    out = export_dir / _OUTPUT_FILENAME
    out.write_text(make_battle_engine_h(project_data=project_data), encoding="utf-8")
    return out
