"""
core/item_table_gen.py — Generate item_table.h from project item_table.

Project data format (in .ngpcraft):
    {
        "item_table": [
            {"name": "Potion",  "type": "ITEM_HEAL",   "value": 20, "rarity": 0, "price": 5,
             "target": "ITEM_TARGET_SELF", "usable_in_battle": True, "consumable": True,
             "max_stack": 9, "msg_use": "Potion used.", "msg_no_effect": "HP already full."},
        ]
    }

All fields after ``sprite_id`` are optional and default to sane values for backward
compat with existing projects (target=SELF, flags=usable+consumable, max_stack=9,
msgs empty/NULL).

Generated output (item_table.h):
    #ifndef ITEM_TABLE_GEN_H
    #define ITEM_TABLE_GEN_H
    /* type IDs, rarity, target enum, flag bits */
    typedef struct {
        u8 type; u8 value; u8 rarity; u8 price; u8 sprite_id;
        u8 target; u8 flags; u8 max_stack;
    } NgpcItem;
    static const NgpcItem g_item_table[ITEM_COUNT] = { ... };
    /* g_item_msgs[] only emitted if at least one msg is non-empty */
    static const NgpcItemMsgs g_item_msgs[ITEM_COUNT] = { ... };
    #endif

Usage:
    from core.item_table_gen import write_item_table_h
    path = write_item_table_h(project_data=data, export_dir=Path("GraphX/gen"))
"""
from __future__ import annotations

import re
from pathlib import Path

_OUTPUT_FILENAME = "item_table.h"


def _sanitize_name(name: str) -> str:
    """Return an UPPER_CASE C identifier from an arbitrary item name."""
    s = re.sub(r"[^a-zA-Z0-9]+", "_", name.strip()).strip("_").upper()
    return s or "UNNAMED"

# Predefined item types — order determines the u8 ID in C
ITEM_TYPES: list[str] = [
    "ITEM_HEAL",
    "ITEM_ATK_UP",
    "ITEM_DEF_UP",
    "ITEM_XP_UP",
    "ITEM_GOLD",
    "ITEM_DICE_PLUS",
    "ITEM_KEY",
    "ITEM_CUSTOM",
]

RARITY_NAMES: list[str] = ["RARITY_COMMON", "RARITY_UNCOMMON", "RARITY_RARE"]

# Battle/inventory targeting — who receives the item effect.
TARGET_NAMES: list[str] = ["ITEM_TARGET_SELF", "ITEM_TARGET_ENEMY", "ITEM_TARGET_NONE"]

# Per-item flag bits packed into the ``flags`` u8.
ITEM_FLAG_USABLE_IN_BATTLE = 0x01
ITEM_FLAG_CONSUMABLE       = 0x02
_DEFAULT_FLAGS = ITEM_FLAG_USABLE_IN_BATTLE | ITEM_FLAG_CONSUMABLE
_DEFAULT_MAX_STACK = 9

_TYPE_TO_ID: dict[str, int] = {t: i for i, t in enumerate(ITEM_TYPES)}
_RARITY_COUNT = len(RARITY_NAMES)
_TARGET_COUNT = len(TARGET_NAMES)


def _escape_c_string(s: str) -> str:
    """Escape a Python string for use as a C string literal body."""
    return (
        s.replace("\\", "\\\\")
         .replace("\"", "\\\"")
         .replace("\n", "\\n")
         .replace("\r", "")
         .replace("\t", "\\t")
    )


def _read_entry(entry: dict) -> dict:
    """Normalise one raw item entry — clamp + fill battle defaults for old data."""
    target_raw = str(entry.get("target", "ITEM_TARGET_SELF") or "ITEM_TARGET_SELF")
    if target_raw not in TARGET_NAMES:
        target_raw = "ITEM_TARGET_SELF"

    if "flags" in entry:
        flags = max(0, min(255, int(entry.get("flags") or 0)))
    else:
        flags = 0
        if bool(entry.get("usable_in_battle", True)):
            flags |= ITEM_FLAG_USABLE_IN_BATTLE
        if bool(entry.get("consumable", True)):
            flags |= ITEM_FLAG_CONSUMABLE

    return {
        "name":       str(entry.get("name", "") or "").strip() or "item",
        "type":       str(entry.get("type", "ITEM_CUSTOM") or "ITEM_CUSTOM"),
        "value":      max(0, min(255, int(entry.get("value", 0) or 0))),
        "rarity":     max(0, min(_RARITY_COUNT - 1, int(entry.get("rarity", 0) or 0))),
        "price":      max(0, min(255, int(entry.get("price", 0) or 0))),
        "sprite_id":  max(0, min(255, int(entry.get("sprite_id", 0) or 0))),
        "target":     target_raw,
        "flags":      flags,
        "max_stack":  max(1, min(255, int(entry.get("max_stack", _DEFAULT_MAX_STACK) or _DEFAULT_MAX_STACK))),
        "msg_use":       str(entry.get("msg_use", "") or ""),
        "msg_no_effect": str(entry.get("msg_no_effect", "") or ""),
    }


def make_item_table_h(*, project_data: dict) -> str:
    """Return the full content of item_table.h as a string."""
    data = project_data if isinstance(project_data, dict) else {}
    raw = data.get("item_table", []) or []
    if not isinstance(raw, list):
        raw = []

    items = [_read_entry(e) for e in raw if isinstance(e, dict)]

    lines: list[str] = [
        "/* item_table.h — auto-generated by NgpCraft Engine */",
        "/* DO NOT EDIT — re-export from the project tab to update. */",
        "#ifndef ITEM_TABLE_GEN_H",
        "#define ITEM_TABLE_GEN_H",
        "",
        "/* ---- Item type IDs ---- */",
    ]
    for i, t in enumerate(ITEM_TYPES):
        lines.append(f"#define {t:<16} {i}u")

    lines += [
        "",
        "/* ---- Rarity levels ---- */",
    ]
    for i, r in enumerate(RARITY_NAMES):
        lines.append(f"#define {r:<18} {i}u")

    lines += [
        "",
        "/* ---- Targeting (who receives the effect) ---- */",
    ]
    for i, t in enumerate(TARGET_NAMES):
        lines.append(f"#define {t:<20} {i}u")

    lines += [
        "",
        "/* ---- Item flag bits (packed in NgpcItem.flags) ---- */",
        f"#define ITEM_FLAG_USABLE_IN_BATTLE  0x{ITEM_FLAG_USABLE_IN_BATTLE:02x}u",
        f"#define ITEM_FLAG_CONSUMABLE        0x{ITEM_FLAG_CONSUMABLE:02x}u",
        "",
        "typedef struct {",
        "    u8 type; u8 value; u8 rarity; u8 price; u8 sprite_id;",
        "    u8 target; u8 flags; u8 max_stack;",
        "} NgpcItem;",
        "",
        "typedef struct { const char *use; const char *no_effect; } NgpcItemMsgs;",
        "",
    ]

    if not items:
        lines += [
            "#define ITEM_COUNT   0u",
            "/* (no items defined) */",
            "",
            "#endif /* ITEM_TABLE_GEN_H */",
            "",
        ]
        return "\n".join(lines)

    lines.append(f"#define ITEM_COUNT   {len(items)}u")
    lines.append("")

    # Per-item index constants (by sanitised name) — usable in C and trigger resolution.
    # Dedupe safe-names so duplicate user-facing names ("item", "item") don't
    # produce duplicate #define macros (C error THC1-322). Append numeric
    # suffix on collision : ITEM_IDX_ITEM, ITEM_IDX_ITEM_2, ...
    lines.append("/* ---- Per-item index constants ---- */")
    _seen: dict[str, int] = {}
    for i, it in enumerate(items):
        base = _sanitize_name(it["name"])
        if base in _seen:
            _seen[base] += 1
            safe = f"{base}_{_seen[base]}"
        else:
            _seen[base] = 1
            safe = base
        lines.append(f"#define ITEM_IDX_{safe:<24} {i}u  /* {it['name']} */")

    lines.append("")
    lines.append(f"static const NgpcItem g_item_table[ITEM_COUNT] = {{")

    for i, it in enumerate(items):
        sep = "," if i < len(items) - 1 else ""
        rarity_name = RARITY_NAMES[it["rarity"]]
        lines.append(
            f"    /* [{i}] {it['name']:<20} */ "
            f"{{ {it['type']:<16}, {it['value']:>3}u, {rarity_name:<18}, "
            f"{it['price']:>3}u, {it['sprite_id']:>3}u, "
            f"{it['target']:<20}, 0x{it['flags']:02x}u, {it['max_stack']:>3}u }}{sep}"
        )

    lines += ["};", ""]

    # Emit the message lookup table only if at least one item has a non-empty
    # template — keeps the ROM footprint zero for projects that don't use them.
    has_msgs = any(it["msg_use"] or it["msg_no_effect"] for it in items)
    if has_msgs:
        lines.append("static const NgpcItemMsgs g_item_msgs[ITEM_COUNT] = {")
        for i, it in enumerate(items):
            sep = "," if i < len(items) - 1 else ""
            use = f"\"{_escape_c_string(it['msg_use'])}\"" if it["msg_use"] else "(const char *)0"
            noe = f"\"{_escape_c_string(it['msg_no_effect'])}\"" if it["msg_no_effect"] else "(const char *)0"
            lines.append(f"    /* [{i}] {it['name']:<20} */ {{ {use}, {noe} }}{sep}")
        lines += ["};", ""]
    else:
        lines += [
            "/* g_item_msgs[] omitted — no item has a non-empty message template. */",
            "",
        ]

    lines += [
        "#endif /* ITEM_TABLE_GEN_H */",
        "",
    ]
    return "\n".join(lines)


def write_item_table_h(*, project_data: dict, export_dir: Path) -> Path:
    """Write ``item_table.h`` to *export_dir*. Returns the written path."""
    export_dir = Path(export_dir)
    export_dir.mkdir(parents=True, exist_ok=True)
    content = make_item_table_h(project_data=project_data)
    out = export_dir / _OUTPUT_FILENAME
    out.write_text(content, encoding="utf-8")
    return out
