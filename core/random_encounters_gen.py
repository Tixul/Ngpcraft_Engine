"""
core/random_encounters_gen.py — Generate random_encounters.h from project
random_encounters mechanic config.

Emits a tiny header consumed by the runtime player update loop. The runtime
calls ``random_encounters_on_step()`` every time the player advances by one
tile/step ; the function rolls the chance and (on hit) calls
``battle_engine_enter(monster_idx)`` with a randomly-picked monster from the
pool.

Output layout::

    #define RE_STEPS_PER_CHECK   16u
    #define RE_CHANCE_PCT        10u
    #define RE_POOL_COUNT         3u
    static const u8 g_re_pool[RE_POOL_COUNT] = { 0u, 2u, 5u };  // monster_idx
    void random_encounters_on_step(void);
"""
from __future__ import annotations

from pathlib import Path

from core.mechanics import get_mechanic_config


_OUTPUT_FILENAME = "random_encounters.h"


def _clamp_u8(v, default: int = 0) -> int:
    try:
        n = int(v if v is not None else default)
    except (TypeError, ValueError):
        n = default
    return max(0, min(255, n))


def make_random_encounters_h(*, project_data: dict) -> str:
    cfg = get_mechanic_config(project_data, "random_encounters")

    steps  = _clamp_u8(cfg.get("steps_per_check"), 16)
    chance = max(0, min(100, _clamp_u8(cfg.get("chance_pct"), 10)))
    pool_raw = cfg.get("enemy_pool", []) or []
    if not isinstance(pool_raw, list):
        pool_raw = []
    pool = [_clamp_u8(x, 0) for x in pool_raw if isinstance(x, int)]

    # Per-scene pool overrides : aggregate from project_data["scenes"].
    # Format = flattened array + per-scene (offset, count) lookup. 0xFFu in
    # the offset means "use default pool" for that scene.
    scenes = project_data.get("scenes", []) if isinstance(project_data, dict) else []
    if not isinstance(scenes, list):
        scenes = []
    scene_overrides: list[list[int]] = []  # parallel to NGP_SCENE_COUNT ; empty list = use default
    for sc in scenes:
        if not isinstance(sc, dict):
            scene_overrides.append([])
            continue
        ov = sc.get("random_encounters_pool")
        if isinstance(ov, list) and ov:
            scene_overrides.append([_clamp_u8(x, 0) for x in ov if isinstance(x, int)])
        else:
            scene_overrides.append([])

    # Flatten the per-scene pools into one array. Build the offset table.
    flat_scene_pools: list[int] = []
    scene_pool_offsets: list[int] = []
    scene_pool_counts:  list[int] = []
    for ov in scene_overrides:
        if ov:
            scene_pool_offsets.append(len(flat_scene_pools))
            scene_pool_counts.append(len(ov))
            flat_scene_pools.extend(ov)
        else:
            scene_pool_offsets.append(0xFF)
            scene_pool_counts.append(0)

    lines: list[str] = [
        "/* random_encounters.h — auto-generated by NgpCraft Engine */",
        "/* DO NOT EDIT — re-export from the project to update. */",
        "#ifndef RANDOM_ENCOUNTERS_GEN_H",
        "#define RANDOM_ENCOUNTERS_GEN_H",
        "",
        f"#define RE_STEPS_PER_CHECK  {steps:>3}u",
        f"#define RE_CHANCE_PCT       {chance:>3}u",
        f"#define RE_POOL_COUNT       {len(pool):>3}u",
        f"#define RE_SCENE_POOLS_LEN  {len(flat_scene_pools):>3}u",
        "",
    ]

    if pool:
        csv = ", ".join(f"{x:>3}u" for x in pool)
        lines.append(f"static const u8 g_re_pool[RE_POOL_COUNT] = {{ {csv} }};")
    else:
        lines.append("/* (default enemy pool empty — runtime uses per-scene only) */")
        lines.append("/* (no g_re_pool emitted to avoid zero-length array warnings) */")
    lines.append("")

    # Per-scene override tables. Always emitted (even all-default) so runtime
    # code compiles without #ifdef. Sentinel 0xFFu means "use default pool".
    if flat_scene_pools:
        csv = ", ".join(f"{x:>3}u" for x in flat_scene_pools)
        lines.append(f"static const u8 g_re_scene_pools[RE_SCENE_POOLS_LEN] = {{ {csv} }};")
    else:
        lines.append("/* (no per-scene pool override — all scenes use g_re_pool) */")
    if scene_pool_offsets:
        off_csv = ", ".join(f"{x:>3}u" for x in scene_pool_offsets)
        cnt_csv = ", ".join(f"{x:>3}u" for x in scene_pool_counts)
        lines.append(f"static const u8 g_re_scene_pool_offset[{len(scene_pool_offsets)}] = {{ {off_csv} }};  /* 0xFFu = use default */")
        lines.append(f"static const u8 g_re_scene_pool_count[{len(scene_pool_counts)}]  = {{ {cnt_csv} }};")
    lines.append("")

    lines += [
        "/* Called from the autorun every frame for scenes where the mech is",
        " * enabled. Pass the current scene id so the per-scene pool override",
        " * can be looked up. Implementation in templates/.../src/ngpng/random_encounters.c. */",
        "void random_encounters_on_step(u8 cur_scene);",
        "",
        "#endif /* RANDOM_ENCOUNTERS_GEN_H */",
        "",
    ]
    return "\n".join(lines)


def write_random_encounters_h(*, project_data: dict, export_dir: Path) -> Path:
    export_dir = Path(export_dir)
    export_dir.mkdir(parents=True, exist_ok=True)
    out = export_dir / _OUTPUT_FILENAME
    out.write_text(make_random_encounters_h(project_data=project_data), encoding="utf-8")
    return out
